def widen_near_surface(x, factor, heights, top=300.0):
    """Scale the departure of each sample from the sample median by `factor` at the ground, tapering linearly to 1 at `top` m (rows are samples, columns the model heights). Median unchanged; factor 1 returns x."""
    z = np.asarray(heights, float)
    f = 1.0 + (float(factor) - 1.0) * np.clip(1.0 - (z - z[0]) / (top - z[0]), 0.0, 1.0)
    med = np.median(x, axis=0, keepdims=True)
    return med + (x - med) * f


class AtmosphereSet:
    """An indexable, sliceable sequence of `Atmosphere` readers over one sample set."""

    def __init__(self, samples, launch_times=None, **reader_kw):
        self.samples, self.reader_kw, self.launch_times = samples, reader_kw, launch_times
        self._n = len(samples["u"])

    def __len__(self):
        return self._n

    def __getitem__(self, i):
        if isinstance(i, slice):
            return [self[j] for j in range(*i.indices(self._n))]
        if i < 0:
            i += self._n
        if not 0 <= i < self._n:
            raise IndexError(f"atmosphere {i} of {self._n}")
        lt = None if self.launch_times is None else self.launch_times[i]
        return Atmosphere(self.samples, i, launch_time=lt, index=i, **self.reader_kw)

    def __iter__(self):
        for i in range(self._n):
            yield self[i]


def _manifest_hash(assets):
    try:
        m = api._assets(assets)["manifest"]
        return hashlib.sha256(json.dumps(m, sort_keys=True, default=str).encode()).hexdigest()[:16]
    except Exception:   # noqa: BLE001
        return "unknown"


class Launch:
    def __init__(self, *args, elevation=None, units="us", seed=0, tz=None, now=None, offline=False, n=1024, assets=None, mode=None, verbose=False, z0=None, era5_store=None, past_wind_spread=1.0, _pool=None, _obs=None, _hrrr=None):
        if units not in ("us", "si"):
            raise ValueError("units must be 'us' or 'si'")
        self._site, self._tz_note = None, None
        lat, lon, when = self._place_and_time(args)
        self.lat, self.lon = float(lat), float(lon)
        self._when = when
        self.units, self.seed, self.n, self.assets, self.mode, self.verbose = units, int(seed), int(n), assets, mode, verbose
        self.offline = bool(offline)
        self._now = now
        self.created = datetime.now(timezone.utc)
        self._elevation_arg = elevation
        self._z0_arg = z0
        self.era5_store = era5_store            # past dates: folder of the local ERA5 profile store (else the TEMPEST_ERA5_STORE environment variable)
        self.past_wind_spread = float(past_wind_spread)      # C4a: widen the PAST-mode wind spread near the ground (GW-1: the past mode is over-confident at 10 m; 1.2 fitted). 1.0 = off
        if not 0.5 <= self.past_wind_spread <= 3.0:
            raise ValueError("past_wind_spread must be between 0.5 and 3 (1.0 = off, 1.2 = the value fitted against station winds)")
        self._obs = dict(_obs or {})
        self._hrrr = dict(_hrrr) if _hrrr else None      # C3: {"u", "v", "note"} HRRR 10 m wind at the pad, applied to the pool by _apply_hrrr
        self._flags = []
        tzname = tz or (self._site.tz if self._site and self._site.tz else None)
        if tzname is None:
            tzname, self._tz_note = guess_tz(self.lat, self.lon), "time-zone-guessed-from-position"
        self.tz_name = tzname
        self.window = when if isinstance(when, Window) else Window(when)
        self._pool = _pool
        self._engine = None
        self._resolved = None
        self._elev = None
        self._frozen = True

    def __setattr__(self, k, v):
        if getattr(self, "_frozen", False) and k not in ("_pool", "_engine", "_resolved", "_elev", "_flags"):
            raise AttributeError("Launch is immutable: use launch.with_(...) to change place, time or settings")
        object.__setattr__(self, k, v)

    # ---- construction helpers
    def _place_and_time(self, args):
        if len(args) == 3 and all(isinstance(a, (int, float)) for a in args[:2]):
            return args[0], args[1], args[2]
        if len(args) == 2 and isinstance(args[0], (tuple, list)):
            return args[0][0], args[0][1], args[1]
        if len(args) == 2 and isinstance(args[0], str):
            self._site = get_site(args[0])
            return self._site.lat, self._site.lon, args[1]
        raise TypeError("Launch(place, when): place is a site name or (lat, lon) or lat, lon as two numbers; when is a time string, a tuple of times or a Window")

    def with_(self, **kw):
        """A new Launch with some settings changed (place/time/observations/units/seed/...)."""
        base = dict(elevation=self._elevation_arg, units=self.units, seed=self.seed, tz=self.tz_name, now=self._now, offline=self.offline, n=self.n, assets=self.assets, mode=self.mode,
                    verbose=self.verbose, z0=self._z0_arg, era5_store=self.era5_store, past_wind_spread=self.past_wind_spread, _obs=self._obs, _hrrr=self._hrrr)
        place = kw.pop("place", None)
        when = kw.pop("when", self._when)
        base.update(kw)
        if place is None:
            args = (self._site.name, when) if self._site else (self.lat, self.lon, when)
        else:
            args = (place, when) if isinstance(place, str) else (place[0], place[1], when)
        return Launch(*args, **base)

    # ---- elevation (spec 0.1): user > site registry > public services / offline DEM > model grid (flagged)
    def elevation_info(self):
        if self._elev is None:
            a = self._elevation_arg
            if a is not None:
                m = names.parse_quantity(a, "length", self.units) if isinstance(a, str) else (float(a) if self.units == "si" else float(a) * 0.3048)
                self._elev = (m, "user", [])
            elif self._site is not None and self._site.elevation_m is not None:
                self._elev = (float(self._site.elevation_m), "site-registry", [])
            else:
                try:
                    if self.offline:
                        from tempest_weather_v2 import _net
                        _net.set_offline(True)
                    e = E.lookup(self.lat, self.lon)
                    self._elev = (float(e.m), e.source, ["elevation-source-" + e.source] if e.note else [])
                except Exception as ex:   # noqa: BLE001  (all services failed, or offline)
                    self._elev = (None, "model-grid", ["elevation-from-model-grid"])
                    if self.verbose:
                        print(f"elevation lookup failed: {ex}")
                finally:
                    if self.offline:
                        from tempest_weather_v2 import _net
                        _net.set_offline(None)
        return self._elev

    # ---- time
    def resolved_window(self):
        if self._resolved is None:
            self._resolved = self.window.resolve(self.lon, self.tz_name, now=self._now)
        return self._resolved

    @property
    def local_time_note(self):
        r = self.resolved_window()
        if r.single:
            t = r.cells_utc[0].astype(datetime)
            tz = timeutil.get_zone(self.tz_name)
            loc = t.replace(tzinfo=timezone.utc).astimezone(tz)
            return f"{loc:%H:%M %Z} = {timeutil.solar_hour(t, self.lon) // 1:02.0f}:{int((timeutil.solar_hour(t, self.lon) % 1) * 60):02d} solar"
        return r.description

    # ---- the pool
    def _ensure_pool(self, n=None):
        pool = self._ensure_pool_raw(n)
        if self._hrrr and not pool.get("hrrr_applied"):
            pool = self._apply_hrrr(pool)
            self._pool = pool
        return pool

    def _apply_hrrr(self, pool):
        """C3: move the near-ground u, v of every sample so the median is HRRR's 10 m wind (weight 1.0) and the spread about it is x0.8, both fading out by 300 m (fitted in scripts/hrrr_vs_asos.py)."""
        from tempest_weather_v2 import hrrr
        s = dict(pool["samples"])
        z = np.asarray(_core.HEIGHTS, float)
        taper = np.clip(1.0 - (z - z[0]) / (hrrr.TAPER_TOP_M - z[0]), 0.0, 1.0)
        for k, target in (("u", self._hrrr["u"]), ("v", self._hrrr["v"])):
            x = np.asarray(s[k], float)
            med = np.median(x[:, 0])
            x = np.median(x, axis=0, keepdims=True) + (x - np.median(x, axis=0, keepdims=True)) * (1.0 + (hrrr.SPREAD_SCALE - 1.0) * taper)
            x = x + hrrr.HRRR_WEIGHT * (target - med) * taper
            s[k] = x.astype(np.float32)
        return dict(pool, samples=s, hrrr_applied=True, flags=list(pool["flags"]) + ["ground-wind-anchored-to-HRRR"])

    def _ensure_pool_raw(self, n=None):
        n = int(n or self.n)
        if self._pool is not None and len(self._pool["samples"]["u"]) >= n:
            return self._pool
        if self._obs:
            self._pool = self._conditioned_pool(n)
            return self._pool
        r = self.resolved_window()
        elev_m, esrc, eflags = self.elevation_info()
        rng = np.random.default_rng(np.random.SeedSequence([self.seed, 1]))
        times = r.sample(n, rng)
        single = r.single
        if single:
            groups = [(r.cells_utc[0].astype(datetime), np.arange(n))]
        else:
            hours = times.astype("datetime64[h]")
            uniq, inv = np.unique(hours, return_inverse=True)
            groups = [(h.astype(datetime), np.flatnonzero(inv == i)) for i, h in enumerate(uniq)]
        samples, infos, mode_count = {}, [], {}
        infos_flags = []
        for gi, (t_utc, pos) in enumerate(groups):
            iso = t_utc.replace(tzinfo=timezone.utc).isoformat()
            atm, info = api.atmosphere_set(self.lat, self.lon, iso, n=len(pos), seed=self.seed * 1009 + gi, elevation=elev_m, mode=self.mode, assets=self.assets, now=self._now, era5_store=self.era5_store)
            if elev_m is None:
                elev_m = float(info["elevation_m"])
            if self.past_wind_spread != 1.0 and info.get("mode") == "past":
                atm = dict(atm)
                for k in ("u", "v"):
                    atm[k] = widen_near_surface(np.asarray(atm[k], float), self.past_wind_spread, _core.HEIGHTS)
                if "past-wind-spread-widened" not in infos_flags:
                    infos_flags.append("past-wind-spread-widened")
            for k in SAMPLE_KEYS:
                v = atm.get(k)
                if v is None:
                    continue
                v = np.asarray(v, np.float32)
                if k not in samples:
                    samples[k] = np.full((n,) + v.shape[1:], np.nan, np.float32)
                samples[k][pos] = v
            infos.append(info)
            mode_count[info["mode"]] = mode_count.get(info["mode"], 0) + len(pos)
        samples["height_agl"] = np.asarray(_core.HEIGHTS, np.float32)
        samples["elevation_m"] = float(elev_m)
        samples["height_asl"] = (elev_m + samples["height_agl"]).astype(np.float32)
        flags = list(eflags) + ["elevation-from-model-grid"] * (esrc == "model-grid" and "elevation-from-model-grid" not in eflags)
        for info in infos:
            for q in info.get("quality", []):
                if q != "nominal" and q not in flags:
                    flags.append(q)
        if self._tz_note:
            flags.append(self._tz_note)
        flags += infos_flags
        if "fallback-mode" in flags:
            asked = self.mode or "the automatic mode"
            warnings.warn(f"Launch asked for {asked} but the tool fell back to the climate generator ({', '.join(f for f in flags if f.startswith(('past-', 'forecast-', 'fallback')))}). "
                          "For past dates give era5_store=<folder> (a local ERA5 profile store) or set TEMPEST_ERA5_STORE; the result is a climate estimate, not that day's weather.", stacklevel=3)
        if not single:
            flags.append("window-hours-independent")
        self._pool = dict(samples=samples, launch_times=times, infos=infos, modes={k: v / n for k, v in mode_count.items()}, elevation_source=esrc, flags=flags,
                          day_share=r.day_share, window=r.description)
        return self._pool

    def _measurements(self):
        return {k: v for k, v in self._obs.items() if not k.startswith("_")}

    def _sensor_sigma(self, base, eng_obs):
        """R2 / IL-156: an observation older than the launch hour, or from a station away from the pad, is not the pad state. Turn its effective gain (age decay x distance and elevation) into an
        observation error for the Gaussian update; no bookkeeping keys = exact pins, as before."""
        from tempest_weather_v2 import obs as O
        o = self._obs
        if not any(k in o for k in ("_age_h", "_dist_km", "_dz_m")):
            return None
        r = self.resolved_window()
        t_mid = r.cells_utc[len(r.cells_utc) // 2]
        night = O.night_weight(timeutil.solar_hour(t_mid.astype("datetime64[s]").astype(datetime), self.lon))
        gain = O.effective_gain(o.get("_age_h", 0.0), o.get("_dist_km", 0.0), o.get("_dz_m", 0.0), night)
        pool = base._ensure_pool()["samples"]
        prior = {("wind_u", 10.0): np.std(np.asarray(pool["u"], float)[:, 0]), ("wind_v", 10.0): np.std(np.asarray(pool["v"], float)[:, 0]),
                 ("temp_K", 2.0): np.std(np.asarray(pool["t2m"], float)), ("pressure_Pa", 0.0): np.std(np.asarray(pool["sp"], float))}
        return {k[0]: O.observation_sigma(prior[k], gain) for k in eng_obs if k in prior}

    def _conditioned_pool(self, n):
        base = Launch.with_(self, _obs=None)
        eng_obs = self._obs_to_engine(base)
        sig = self._sensor_sigma(base, eng_obs)
        eng = base.engine().conditioned(eng_obs, sensor_sigma=sig, soft=sig is not None)       # weighted observations are soft: the observed columns move with the error, they are not pinned
        u = np.random.default_rng(np.random.SeedSequence([self.seed, 2])).random((n, 16))
        out = eng.sample_sobol(u)
        s = {k: np.asarray(out[k], np.float32) for k in ("u", "v", "T", "RH", "p", "rho", "a", "t2m", "sp", "rh2m") if k in out}
        s["w"] = np.asarray(out["w"], np.float32) if "w" in out else np.zeros_like(s["u"])
        for k in ("gust_mu", "gust_beta"):
            if k in out:
                s[k] = np.asarray(out[k], np.float32)
        elev = float(base._ensure_pool()["samples"]["elevation_m"])
        s["height_agl"] = np.asarray(_core.HEIGHTS, np.float32)
        s["elevation_m"] = elev
        s["height_asl"] = (elev + s["height_agl"]).astype(np.float32)
        bp = base._ensure_pool()
        return dict(samples=s, launch_times=bp["launch_times"][:1].repeat(n), infos=bp["infos"], modes=bp["modes"], elevation_source=bp["elevation_source"],
                    flags=list(bp["flags"]) + ["conditioned-on-%d-measurements-not-yet-validated" % len(self._measurements())] + ([f"observation-from-{self._obs['_source']}"] if "_source" in self._obs else []), day_share=bp["day_share"], window=bp["window"])

    def _obs_to_engine(self, base):
        o, eng_obs = self._measurements(), {}
        if "wind_10m" in o:
            spd = names.parse_quantity(o["wind_10m"], "speed", self.units)
            frm = float(o.get("wind_from_deg", 0.0))
            eng_obs[("wind_u", 10.0)] = -spd * np.sin(np.radians(frm))
            eng_obs[("wind_v", 10.0)] = -spd * np.cos(np.radians(frm))
        if "temperature" in o:
            eng_obs[("temp_K", 2.0)] = names.parse_quantity(o["temperature"], "temperature", self.units) + 273.15
        if "station_pressure" in o:
            eng_obs[("pressure_Pa", 0.0)] = names.parse_quantity(o["station_pressure"], "pressure", self.units) * 100.0
        elif "altimeter" in o:                                           # a sea-level altimeter setting (METAR "A3002"): back to pad pressure through the standard atmosphere
            elev = float(base._ensure_pool()["samples"]["elevation_m"])
            eng_obs[("pressure_Pa", 0.0)] = float(W.station_pressure_hpa(names.parse_quantity(o["altimeter"], "pressure", self.units), elev)) * 100.0
        return eng_obs

    def observe(self, wind_10m=None, wind_from_deg=None, temperature=None, station_pressure=None, altimeter=None, sounding=None, age_hours=None, distance_km=None, elevation_diff_m=None, source=None):
        """A NEW Launch conditioned on launch-day measurements at the pad: 10 m wind speed and direction (from), 2 m temperature, pad (station) pressure, or a sea-level altimeter setting
        (what a METAR reports; converted to pad pressure through the standard atmosphere). Numbers use the Launch's units, strings carry their own ("14 mph", "82 F", "29.92 inHg").
        `sounding="auto"` needs the sounding module (R2, not built)."""
        if station_pressure is not None and altimeter is not None:
            raise ValueError("give station_pressure or altimeter, not both")
        # age_hours / distance_km / elevation_diff_m (station minus pad) weight the measurement by its representativeness (see obs.py); without them the values are pinned exactly
        if sounding is not None:
            raise NotImplementedError("sounding conditioning comes with the R2 module (tempest_weather_v2.sounding); pass wind_10m / wind_from_deg / temperature for now")
        obs = dict(self._obs)
        for k, v in (("wind_10m", wind_10m), ("wind_from_deg", wind_from_deg), ("temperature", temperature), ("station_pressure", station_pressure), ("altimeter", altimeter)):
            if v is not None:
                obs[k] = v
        if ("station_pressure" in obs and "altimeter" in obs) and (station_pressure is not None or altimeter is not None):
            obs.pop("altimeter" if station_pressure is not None else "station_pressure")      # the newer value replaces an earlier one of the other kind
        if "wind_from_deg" in obs and "wind_10m" not in obs:
            raise ValueError("a wind direction needs a wind speed too (wind_10m=...)")
        for k, v in (("_age_h", age_hours), ("_dist_km", distance_km), ("_dz_m", elevation_diff_m), ("_source", source)):
            if v is not None:
                obs[k] = v
        if not {k for k in obs if not k.startswith("_")}:
            raise ValueError("give at least one measurement")
        return self.with_(_obs=obs)

    def observe_metar(self, text):
        """A NEW Launch conditioned on a METAR/SPECI report (wind, temperature, altimeter setting): `launch.observe_metar("KTCS 241553Z 19002KT 10SM CLR 23/12 A3012")`. The station is
        usually not at the pad: the trust line says so, and a station far from or much higher than the pad is a weak stand-in for the pad's own wind and temperature."""
        from tempest_weather_v2 import metar
        m = metar.parse(text)
        kw = m.observation_kwargs()
        if not kw:
            raise ValueError("that METAR has nothing usable (a variable-direction wind alone cannot be used)")
        return self.observe(**kw)

    def observe_hrrr(self, fetch=None, now=None):
        """A NEW Launch whose ground wind (below 300 m) is anchored to HRRR's 10 m wind at the pad: the sample median moves to HRRR's value and the spread about it shrinks to 0.8x (weights fitted on station winds,
        scripts/hrrr_vs_asos.py). Needs one launch time. HRRR is near-analysis quality only for past and present hours; at long forecast lead the benefit is not measured (the trust line says so)."""
        r = self.resolved_window()
        if not r.single:
            raise ValueError("observe_hrrr needs a single launch time, not a window")
        t0 = r.cells_utc[0].astype("datetime64[s]").astype(datetime).replace(tzinfo=timezone.utc)
        u, v, note = _hrrr.fetch_wind(self.lat, self.lon, t0, now=now, fetch=fetch)
        return self.with_(_hrrr=dict(u=u, v=v, note=note))

    def observe_latest(self, max_km=150.0, hours=6, k=3, fetch=None, now=None):
        """A NEW Launch conditioned on the latest METAR of the nearest station that has a usable report before the launch time (IEM, no key; `fetch` and `now` are injectable for tests / offline replay).
        The report is weighted by its age, its distance and its height difference from the pad, and the trust line names station, distance and age."""
        from datetime import timezone as _tz
        from tempest_weather_v2 import obs as O
        r = self.resolved_window()
        t0 = r.cells_utc[len(r.cells_utc) // 2].astype("datetime64[s]").astype(datetime).replace(tzinfo=_tz.utc)
        stop = min(t0, now) if now is not None else t0                       # a report cannot be newer than the real clock
        elev = float(self._ensure_pool()["samples"]["elevation_m"]) if self._pool is not None else (self.elevation_info()[0] or 0.0)
        tried = []
        for sid, dist, el in O.nearest(self.lat, self.lon, k=k, max_km=max_km):
            t, m = O.latest_report(sid, stop, hours=hours, fetch=fetch)
            tried.append(sid)
            kw = m.observation_kwargs() if m is not None else {}
            if not kw:
                continue
            return self.observe(**kw, age_hours=(t0 - t).total_seconds() / 3600.0, distance_km=dist, elevation_diff_m=el - elev, source=f"METAR {sid} {t:%d %H:%MZ}")
        near = ", ".join(f"{i} {d:.0f} km" for i, d, _ in O.nearest(self.lat, self.lon, k=k, max_km=max_km)) or f"none within {max_km:.0f} km"
        raise LookupError(f"no usable METAR in the {hours} h before launch from the nearest stations ({near}; tried {tried or 'none'}). Pass the report yourself with observe_metar(text).")

    # ---- trust, provenance
    @property
    def trust(self):
        p = self._ensure_pool()
        m = p["modes"]
        names_ = {"ai": "Climate estimate: typical range for this date, not a forecast", "past": "Past date: ERA5 corrected to balloons", "forecast": "Forecast (ECMWF), tested on 2022 data"}
        if len(m) == 1:
            text = names_.get(next(iter(m)), f"mode {next(iter(m))}")
        else:
            text = "Mixed: " + ", ".join(f"{100 * v:.0f}% {'forecast' if k == 'forecast' else 'climate' if k == 'ai' else 'past'}" for k, v in sorted(m.items(), key=lambda kv: -kv[1])) + " (window spans a mode limit)"
        if "fallback-mode" in p["flags"]:
            text += " (the mode you asked for was not available: see flags)"
        if self._hrrr:
            text += f"; ground wind anchored to {self._hrrr['note']} (weights fitted on station winds; not validated beyond near-analysis)"
        if self._measurements():
            text += f"; conditioned on {len(self._measurements())} measurements (not yet validated)"
            o = self._obs
            if "_source" in o:
                detail = [f"from {o['_source']}"]
                if "_dist_km" in o:
                    detail.append(f"{o['_dist_km']:.0f} km from the pad")
                if "_dz_m" in o:
                    detail.append(f"{o['_dz_m']:+.0f} m in height")
                if "_age_h" in o:
                    detail.append(f"{o['_age_h']:.1f} h old")
                text += " (" + ", ".join(detail) + "; gain fitted on station pairs, see obs.py)"
        return text

    @property
    def provenance(self):
        p = self._ensure_pool()
        info0 = p["infos"][0] if p["infos"] else {}
        return dict(package_version=__version__, format_version=FORMAT_VERSION, asset_manifest_hash=_manifest_hash(self.assets), modes=p["modes"], seed=self.seed,
                    now=str(self._now) if self._now else None, elevation_source=p["elevation_source"], source=info0.get("source"), valid_utc=info0.get("valid_utc"), window=p["window"],
                    forecast_model=("IFS (Open-Meteo)" if "forecast" in p["modes"] else None))

    # ---- derived per-sample quantities (SI internal)
    def _derive(self, s, times=None):
        z = np.asarray(s["height_agl"], float)
        u, v = np.asarray(s["u"], float), np.asarray(s["v"], float)
        t2m, sp, rh2m = (np.asarray(s[k], float) for k in ("t2m", "sp", "rh2m"))
        elev = float(s["elevation_m"])
        d = {"elevation": np.full(len(u), elev), "temperature": t2m - 273.15, "station_pressure": sp / 100.0}
        d["pressure"] = W.altimeter_setting_hpa(d["station_pressure"], elev)
        d["mslp"] = W.mslp_hpa(d["station_pressure"], t2m, elev)
        spd, frm, um, vm = W.drift_wind(u, v, z)
        d["wind_speed"], d["wind_from_deg"], d["_um"], d["_vm"] = spd, frm, um, vm
        d["wind_10m"] = np.hypot(u[:, 0], v[:, 0])
        d["wind_10m_from_deg"] = W.wind_from_deg(u[:, 0], v[:, 0])
        k3 = z <= 3000.0
        u3, v3 = u[:, k3].mean(1), v[:, k3].mean(1)
        d["wind_3km"], d["wind_3km_from_deg"] = np.hypot(u3, v3), W.wind_from_deg(u3, v3)
        if s.get("gust_mu") is not None and np.isfinite(np.asarray(s["gust_mu"], float)).all():
            d["gust"] = np.maximum(np.asarray(s["gust_mu"], float) - np.asarray(s["gust_beta"], float) * np.log(-np.log(0.5)), d["wind_10m"])
        d["humidity"] = rh2m
        d["dew_point"] = W.dew_point_k(t2m, rh2m) - 273.15
        q = _core.mixing_q(t2m, rh2m, sp)
        rho = sp / (_core.RD * t2m * (1 + (_core.RV / _core.RD - 1) * q))
        d["density"], d["density_ratio"], d["density_altitude"] = rho, rho / 1.225, W.density_altitude_m(rho)
        d["surface_roughness_m"] = self._z0_samples(d["wind_10m_from_deg"], times, len(u))
        d["max_wind_shear"], d["max_wind_shear_alt"] = W.max_shear(u, v, z)
        d["upper_wind_max"], d["upper_wind_max_alt"] = W.upper_wind_max(u, v, z)
        return d

    def _z0_samples(self, wind_from, times, n):
        """R1: z0 per sample from the user's value, else the directional land-cover map (the sample's own 10 m wind direction and month), else the old fixed 0.03 m (flagged)."""
        if self._z0_arg:
            return np.full(n, float(self._z0_arg))
        rmap = roughness.load_default()
        if rmap is not None and rmap.covers(self.lat, self.lon):
            months = (times.astype("datetime64[M]").astype(int) % 12 + 1) if times is not None else np.full(n, self.resolved_window().cells_utc[0].astype("datetime64[M]").astype(int) % 12 + 1)
            out = np.empty(n)
            for m in np.unique(months):
                sel = months == m
                out[sel] = rmap.z0(self.lat, self.lon, wind_from[sel], int(m))
            if np.isfinite(out).all():
                return out
        if "z0-default-0.03" not in self._flags:
            self._flags.append("z0-default-0.03")
        return np.full(n, Z0_DEFAULT)

    def z0(self):
        """The median surface roughness (m) for this launch, e.g. for the Dryden turbulence (`z0_roughness_m=`)."""
        pool = self._ensure_pool()
        return float(np.median(self._derive(pool["samples"], pool["launch_times"])["surface_roughness_m"]))

    @staticmethod
    def _summ(name, x, sel=None):
        x = x if sel is None else x[sel]
        return float(np.median(x))

    # ---- Call 1: weather()
    def weather(self, percentile=None, all=False, by="wind_speed", marginal=False, ras_profiles=False):
        """Launch-site numbers. percentile (one number or a list) = the value the weather stays below p % of the time, coupled through the lead variable `by`; marginal=True gives every field its own
        percentile ('not one consistent day'). ras_profiles=True returns [P10, P50, P90]."""
        if ras_profiles:
            return self.weather(percentile=[10, 50, 90], all=all, by=by, marginal=marginal)
        if isinstance(percentile, (list, tuple)):
            return [self.weather(percentile=p, all=all, by=by, marginal=marginal) for p in percentile]
        pool = self._ensure_pool()
        s = pool["samples"]
        d = self._derive(s, pool["launch_times"])
        n = len(d["elevation"])
        flags = list(pool["flags"]) + [f for f in self._flags if f not in pool["flags"]]
        notes = [f"uniform wind assumes a {int(round(W.FLIGHT_DEFAULT['apogee_m'] / 0.3048)):,} ft flight (main at 1,000 ft)"]
        if percentile is None:
            sel, label = None, f"{self.local_time_note}  |  median of {n} atmospheres"
        else:
            p = float(percentile)
            if not 0.0 < p < 100.0:
                raise ValueError("percentile must be between 0 and 100")
            if by not in d or by.startswith("_"):
                raise ValueError(f"by= must be one of the numeric fields, e.g. 'wind_speed'; got {by!r}")
            if marginal:
                sel, label = None, f"{self.local_time_note}  |  each field at its own {p:g}th percentile (NOT one consistent day)"
                flags.append("marginal-percentiles")
            else:
                rank = (np.argsort(np.argsort(d[by])) + 0.5) / n
                width = max(0.05, 12.5 / n)
                sel = np.abs(rank - p / 100.0) <= width
                label = f"{self.local_time_note}  |  {p:g}th percentile of {by} (other fields: typical values for such a day, {int(sel.sum())} atmospheres)"
        vals = {}
        for k, x in d.items():
            if k.startswith("_"):
                continue
            if percentile is not None and marginal and not k.endswith("_deg"):
                vals[k] = float(np.percentile(x, float(percentile)))
            elif percentile is not None and not marginal and k == by:
                vals[k] = float(np.percentile(x, float(percentile)))
            else:
                vals[k] = self._summ(k, x, sel)
        for ang, comp in (("wind_from_deg", ("_um", "_vm")),):          # circular quantities from the components
            xs = slice(None) if sel is None else sel
            vals[ang] = float(W.wind_from_deg(np.median(d[comp[0]][xs]), np.median(d[comp[1]][xs])))
        for ang, (a, b) in (("wind_10m_from_deg", ("u", "v")),):
            xs = slice(None) if sel is None else sel
            vals[ang] = float(W.wind_from_deg(np.median(np.asarray(s[a], float)[xs, 0]), np.median(np.asarray(s[b], float)[xs, 0])))
        xs = slice(None) if sel is None else sel
        if "gust" in vals:                                                    # turbulence estimate for OpenRocket: gust = mean + 3 sigma, so sigma = (gust - mean) / 3 (an estimate, not a measurement)
            vals["wind_10m_std"] = max(vals["gust"] - vals["wind_10m"], 0.0) / 3.0
        else:
            flags.append("gust-model-not-available")
        site_decl = self._site.declination() if self._site else W.declination_deg(self.lat, self.lon, 2026.9)
        return Weather(vals, units=self.units, all_fields=all, label=label, flags=flags, provenance=self.provenance, trust=self.trust, declination=site_decl, notes=notes)

    # ---- Call 2: distribution()
    def distribution(self, variables, spread="full"):
        """Best-fit distribution per parameter and its empirical quantile table. spread='typical' needs weather-only variability, which the pool does not separate: it is flagged and 'full' is used."""
        if spread not in ("full", "typical"):
            raise ValueError("spread must be 'full' or 'typical'")
        d = self._derive(self._ensure_pool()["samples"])
        out = {}
        for name in ([variables] if isinstance(variables, str) else variables):
            key = names.resolve_name(name)
            if key not in d:
                raise ValueError(f"{key} has no per-sample values here")
            r = stats.fit_best(d[key])
            r["units"] = names.unit_label(key, self.units)
            r["quantiles_display"] = {p: float(names.to_units(key, v, self.units)) for p, v in r["quantiles"].items()}
            r["spread"] = "full" if spread == "full" else "full (typical-only spread not separable: flagged spread-typical-unavailable)"
            out[key] = r
        return out

    # ---- Call 3: couple()
    def couple(self, variables, method="whole_sample", k=None):
        d = self._derive(self._ensure_pool()["samples"])
        keys = [names.resolve_name(v) for v in variables]
        for kk in keys:
            if kk not in d:
                raise ValueError(f"{kk} has no per-sample values here")
        data = np.stack([d[kk] for kk in keys], 1)
        c = stats.Coupled(data, keys, method=method, k=k, seed=self.seed)
        c.display_units = {kk: names.unit_label(kk, self.units) for kk in keys}
        return c

    # ---- Call 4: atmospheres()
    def atmospheres(self, n=None, **reader_kw):
        pool = self._ensure_pool(n)
        s = pool["samples"]
        n = int(n or self.n)
        sub = {k: (v[:n] if isinstance(v, np.ndarray) and v.ndim >= 1 and len(v) >= n and k not in ("height_agl", "height_asl") else v) for k, v in s.items()}
        return AtmosphereSet(sub, launch_times=pool["launch_times"][:n], **reader_kw)

    # ---- Call 5: engine()
    def engine(self, **kw):
        if self._engine is None:
            from tempest_weather.flight import TempestFlightSimEngine
            pool = self._ensure_pool() if not self._obs else Launch.with_(self, _obs=None)._ensure_pool()
            s = pool["samples"]
            atm = {k: np.asarray(s[k], float) for k in ("u", "v", "T", "RH", "t2m", "sp", "rh2m") if k in s}
            for k in ("w", "gust_mu", "gust_beta"):
                if k in s:
                    atm[k] = np.asarray(s[k], float)
            self._engine = TempestFlightSimEngine(atm=atm, info={"elevation_m": float(s["elevation_m"])}, seed=self.seed, **kw)
        return self._engine

    # ---- save / load (I-8)
    def save(self, path):
        pool = self._ensure_pool()
        s = pool["samples"]
        meta = dict(format_version=FORMAT_VERSION, package_version=__version__, lat=self.lat, lon=self.lon, tz=self.tz_name, units=self.units, seed=self.seed, n=self.n,
                    site=self._site.name if self._site else None, window=pool["window"], modes=pool["modes"], elevation_source=pool["elevation_source"], flags=pool["flags"],
                    provenance=self.provenance, day_share=pool["day_share"], obs={k: str(v) for k, v in self._obs.items()})
        arrays = {f"s_{k}": np.asarray(v) for k, v in s.items()}
        with open(path, "wb") as f:                           # a file handle: np.savez would otherwise append ".npz" to the name
            np.savez(f, launch_times=pool["launch_times"].astype("datetime64[s]").astype("int64"), meta=np.array(json.dumps(meta, default=str)), **arrays)
        return str(path)

    @classmethod
    def load(cls, path):
        with np.load(path, allow_pickle=False) as z:
            meta = json.loads(str(z["meta"]))
            if meta.get("format_version", 0) > FORMAT_VERSION:
                raise ValueError(f"{path} was written by a newer version (format {meta['format_version']})")
            s = {k[2:]: z[k] for k in z.files if k.startswith("s_")}
            if "elevation_m" in s:
                s["elevation_m"] = float(s["elevation_m"])
            lt = z["launch_times"].astype("datetime64[s]")
        pool = dict(samples=s, launch_times=lt, infos=[{"mode": m, "quality": []} for m in meta["modes"]], modes=meta["modes"], elevation_source=meta["elevation_source"], flags=meta["flags"],
                    day_share=meta.get("day_share", {}), window=meta["window"])
        L = cls(meta["lat"], meta["lon"], str(lt[0]) + "+00:00", units=meta["units"], seed=meta["seed"], tz=meta["tz"], n=meta["n"], elevation=float(s["elevation_m"]) if meta["units"] == "si" else float(s["elevation_m"]) / 0.3048, _pool=pool)
        if meta.get("site"):
            object.__setattr__(L, "_site", get_site(meta["site"]))
        object.__setattr__(L, "_loaded", True)
        return L

    def stale(self, now=None):
        """C1: True when the real clock has moved into a mode that differs from the one used (e.g. a climate estimate for a time that has since become a forecast)."""
        now = now or datetime.now(timezone.utc)
        return (now - self.created).total_seconds() > 6 * 3600

    def __repr__(self):
        site = self._site.name if self._site else f"{self.lat:.4f},{self.lon:.4f}"
        return f"Launch({site!r}, {self.window!r}, units={self.units!r}, seed={self.seed})"


class Launches:
    """T1/T2: many launches asked at once (a list of `Launch`, or one place over several times). Each member keeps its own cached pool; the loop only saves you writing it.

        runs = Launches.over_times("spaceport_america", ["2027-06-16 08:00", "2027-06-16 10:00"], n=512)
        runs.weather()                       # list of Weather, one per launch
        runs.table("wind_speed")             # (median, p10, p90) per launch
    """

    def __init__(self, launches):
        self.launches = list(launches)
        if not self.launches:
            raise ValueError("Launches needs at least one Launch")

    @classmethod
    def over_times(cls, *place, times, **kw):
        return cls(Launch(*place, t, **kw) for t in times)

    def __len__(self):
        return len(self.launches)

    def __getitem__(self, i):
        return self.launches[i]

    def weather(self, **kw):
        return [L.weather(**kw) for L in self.launches]

    def table(self, variable):
        """(len, 3) array of the median, 10th and 90th percentile of one variable (derived SI-style units, as couple() uses) per launch."""
        key = names.resolve_name(variable)
        out = []
        for L in self.launches:
            x = L._derive(L._ensure_pool()["samples"])[key]
            out.append(np.nanpercentile(x, [50, 10, 90]))
        return np.array(out)
