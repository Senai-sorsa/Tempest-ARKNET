"""`Launch`: set place and time once, then ask (spec 1.x, I-1, I-4, I-7, I-8, 5). Immutable; the atmosphere pool is built lazily on the first call and cached on the instance.

    from tempest_weather_v2 import Launch, Window
    launch = Launch("spaceport_america", "2027-06-16 10:00")           # or Launch(32.99, -106.97, "2027-06-16 10:00"); elevation="4600 ft", units="si", seed=0
    r = launch.weather()                  # RASAero / OpenRocket numbers;  launch.weather(percentile=90), launch.weather(all=True)
    d = launch.distribution(["wind_speed", "temperature"])             # best-fit distribution per parameter
    c = launch.couple(["temperature", "wind_speed"], method="t_copula")  # joint draws
    atms = launch.atmospheres(1000)       # indexable sequence of Atmosphere readers (see readers.py)
    eng = launch.engine()                 # the flight-sim engine over the pool
    lc = launch.observe(wind_10m="14 mph", wind_from_deg=240, temperature="82 F")   # a NEW Launch conditioned on launch-day measurements
`Launch.save(path)` / `Launch.load(path)` archive the pool and provenance (.tempest = a numpy archive).
Windows (uncertain launch times) are drawn per sample; samples are grouped by UTC hour and each hour is generated by the existing generator (hours are not yet tied by the hourly copula: flagged).
"""
